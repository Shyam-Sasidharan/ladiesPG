import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const env=await fs.readFile('.env','utf8');
const value=name=>env.match(new RegExp(`^${name}=(.*)$`,'m'))?.[1].trim().replace(/^"|"$/g,'');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await fs.mkdir('storage/app/qa',{recursive:true});
try {
 await page.goto('http://127.0.0.1:8000/login');
 await page.getByLabel('Email address').fill(value('ADMIN_EMAIL'));
 await page.locator('input[name="password"]').fill(value('ADMIN_PASSWORD'));
 await page.getByRole('button',{name:'Sign in to Haven'}).click();
 await page.waitForURL('http://127.0.0.1:8000/');
 await page.screenshot({path:'storage/app/qa/dashboard-desktop.png',fullPage:true});
 assert.equal(await page.locator('.stat-card').count(),8);
 await page.goto('http://127.0.0.1:8000/allocation');
 await page.locator('.bed.available').first().click();
 await page.locator('#allocate-form').waitFor({state:'visible'});
 assert.match(await page.locator('#detail-status').textContent(),/Available/);
 await page.screenshot({path:'storage/app/qa/allocation-desktop.png',fullPage:true});
 await page.locator('.bed.occupied').first().click();
 await page.locator('#occupied-detail').waitFor({state:'visible'});
 assert.ok((await page.locator('#detail-resident').textContent()).length>0);
 assert.equal(await page.locator('#allocate-form').isVisible(),false);
 await page.locator('.bed.maintenance').first().click();
 await page.locator('#blocked-detail').waitFor({state:'visible'});
 await page.goto('http://127.0.0.1:8000/billing');
 await page.locator('[data-payment]:not([disabled])').first().click();
 await page.locator('#payment-dialog').waitFor({state:'visible'});
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:8000/');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'storage/app/qa/dashboard-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Toggle navigation'}).click();
 await page.locator('#sidebar').getByRole('link',{name:'Room Allocation'}).click();
 await page.locator('.bed.available').first().click();
 await page.locator('#allocate-form').waitFor({state:'visible'});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'storage/app/qa/allocation-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: desktop/mobile login, dashboard, bed availability, occupied details, maintenance blocking, payment modal, navigation, overflow and JavaScript checks.');
} finally { await browser.close(); }
